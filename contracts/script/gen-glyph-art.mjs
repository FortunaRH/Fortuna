import fs from "node:fs";

// Reads the braille art (app/assets/face.txt) and writes GlyphArt.sol.
// Each braille cell (U+2800..U+28FF) maps to its 8-dot byte value (0..255).
const src = fs.readFileSync("../../app/assets/face.txt", "utf8").replace(/\r\n?/g, "\n");
const lines = src.split("\n");
while (lines.length && lines[lines.length - 1].trim() === "") lines.pop();

const height = lines.length;
let width = 0;
for (const line of lines) width = Math.max(width, [...line].length);

const bytes = [];
for (const line of lines) {
  const chars = [...line];
  for (let c = 0; c < width; c++) {
    const code = (chars[c] ?? "\u2800").codePointAt(0);
    bytes.push(code - 0x2800);
  }
}

let hex = "";
for (const b of bytes) hex += b.toString(16).padStart(2, "0");

const out = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

/// @notice Braille portrait art (${width}x${height} cells). Generated by gen-glyph-art.mjs.
library GlyphArt {
    uint256 internal constant WIDTH = ${width};
    uint256 internal constant HEIGHT = ${height};
    bytes internal constant DATA = hex"${hex}";
}
`;

fs.writeFileSync("../src/GlyphArt.sol", out);
console.log(`GlyphArt.sol written: WIDTH=${width} HEIGHT=${height} cells=${bytes.length} hexLen=${hex.length}`);
